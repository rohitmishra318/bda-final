"""
setup_flink_resources.py
========================
After running generate_synthetic_data.py and training the ML model,
run this script to:
  1. Copy reference CSVs into the Flink Java source resources
     (so they get bundled into the JAR by Maven)
  2. Copy the exported ML model JSON into Flink resources
  3. Download the Flink-Kafka connector JAR (needed for Docker Compose)

Run:
  python setup_flink_resources.py

Requirements: requests (pip install requests)
"""

import shutil
import sys
import urllib.request
from pathlib import Path

BASE = Path(__file__).resolve().parent

# â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€
# Paths
# â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€

FLINK_RESOURCES = BASE / "flink-java" / "src" / "main" / "resources"
FLINK_REFERENCE_DIR = FLINK_RESOURCES / "reference"
FLINK_MODELS_DIR    = FLINK_RESOURCES / "models"
FLINK_LIB_DIR       = BASE / "flink" / "lib"

# Source data files (generated by generate_synthetic_data.py)
SRC_EVENT_CATALOGUE     = BASE / "data" / "reference" / "event_catalogue.csv"
SRC_NETWORK_HIERARCHY   = BASE / "data" / "reference" / "network_hierarchy.csv"
SRC_IF_MODEL_JSON       = BASE / "ml" / "models" / "isolation_forest_model.json"

# Destination paths inside Flink resources (bundled into JAR)
DST_EVENT_CATALOGUE     = FLINK_REFERENCE_DIR / "event_catalogue.csv"
DST_NETWORK_HIERARCHY   = FLINK_REFERENCE_DIR / "network_hierarchy.csv"
DST_IF_MODEL_JSON       = FLINK_MODELS_DIR    / "isolation_forest_model.json"

# Flink SQL Kafka connector JAR
KAFKA_CONNECTOR_JAR_URL = (
    "https://repo1.maven.org/maven2/org/apache/flink/"
    "flink-sql-connector-kafka/5.0.0-2.2/"
    "flink-sql-connector-kafka-5.0.0-2.2.jar"
)
KAFKA_CONNECTOR_JAR_DST = FLINK_LIB_DIR / "flink-sql-connector-kafka-5.0.0-2.2.jar"

errors = []

# â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€
# Step 1: Copy reference CSVs â†’ Flink resources
# â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€

FLINK_REFERENCE_DIR.mkdir(parents=True, exist_ok=True)

for src, dst, label in [
    (SRC_EVENT_CATALOGUE, DST_EVENT_CATALOGUE, "event_catalogue.csv"),
    (SRC_NETWORK_HIERARCHY, DST_NETWORK_HIERARCHY, "network_hierarchy.csv"),
]:
    if not src.exists():
        msg = f"[MISSING] {src}\n  â†’ Run generate_synthetic_data.py first!"
        print(msg)
        errors.append(msg)
    else:
        shutil.copy2(src, dst)
        print(f"[OK] Copied {label} â†’ {dst.relative_to(BASE)}")

# â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€
# Step 2: Copy ML model JSON â†’ Flink resources
# â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€

FLINK_MODELS_DIR.mkdir(parents=True, exist_ok=True)

if not SRC_IF_MODEL_JSON.exists():
    msg = (
        f"[MISSING] {SRC_IF_MODEL_JSON}\n"
        "  â†’ Run these first:\n"
        "      python ml/train_isolation_forest.py\n"
        "      python ml/export_isolation_forest_json.py"
    )
    print(msg)
    errors.append(msg)
else:
    shutil.copy2(SRC_IF_MODEL_JSON, DST_IF_MODEL_JSON)
    print(f"[OK] Copied isolation_forest_model.json â†’ {DST_IF_MODEL_JSON.relative_to(BASE)}")

# â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€
# Step 3: Download Flink-Kafka connector JAR
# â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€

FLINK_LIB_DIR.mkdir(parents=True, exist_ok=True)

if KAFKA_CONNECTOR_JAR_DST.exists():
    print(f"[SKIP] {KAFKA_CONNECTOR_JAR_DST.name} already exists")
else:
    print(f"\nDownloading Flink-Kafka connector JAR (~15 MB)...")
    print(f"  URL: {KAFKA_CONNECTOR_JAR_URL}")
    print(f"  Destination: {KAFKA_CONNECTOR_JAR_DST.relative_to(BASE)}")
    try:
        def progress(block_num, block_size, total_size):
            downloaded = block_num * block_size
            if total_size > 0:
                pct = min(downloaded / total_size * 100, 100)
                bar = int(pct / 5)
                print(f"\r  [{'#' * bar}{' ' * (20 - bar)}] {pct:.0f}%", end="", flush=True)

        urllib.request.urlretrieve(KAFKA_CONNECTOR_JAR_URL, KAFKA_CONNECTOR_JAR_DST, progress)
        print()
        print(f"[OK] Downloaded {KAFKA_CONNECTOR_JAR_DST.name} ({KAFKA_CONNECTOR_JAR_DST.stat().st_size // 1024:,} KB)")
    except Exception as e:
        msg = f"[FAIL] Could not download JAR: {e}\n  â†’ Download manually from:\n  {KAFKA_CONNECTOR_JAR_URL}\n  Save to: flink/lib/"
        print(msg)
        errors.append(msg)

# â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€
# Summary
# â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€

print()
print("=" * 55)
if errors:
    print(f"Setup incomplete â€” {len(errors)} issue(s) found:")
    for e in errors:
        print(f"  â€¢ {e}")
    sys.exit(1)
else:
    print("Flink resource setup complete!")
    print("=" * 55)
    print()
    print("What was set up:")
    print(f"  {DST_EVENT_CATALOGUE.relative_to(BASE)}")
    print(f"  {DST_NETWORK_HIERARCHY.relative_to(BASE)}")
    print(f"  {DST_IF_MODEL_JSON.relative_to(BASE)}")
    print(f"  {KAFKA_CONNECTOR_JAR_DST.relative_to(BASE)}")
    print()
    print("Now build the Flink JAR:")
    print("  cd flink-java")
    print("  mvn clean package")
    print()
    print("Then start infrastructure:")
    print("  docker network create event-stack-net")
    print("  docker compose -f docker-compose.example.yml up -d")

